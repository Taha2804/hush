import wordlib as W

cats = {c['id']: c for c in W.load_categories()}
lists = W.Lists()

def fix_word(w):
    """Fix obvious casing issues."""
    w = w.strip()
    known_caps = {
        'New orleans': 'New Orleans', 'kuala lumpur': 'Kuala Lumpur',
        'sao paulo': 'Sao Paulo', 'united states': 'United States',
        'Costa rica': 'Costa Rica', 'ivory coast': 'Ivory Coast',
        'Sierra leone': 'Sierra Leone', 'El salvador': 'El Salvador',
        'Santa claus': 'Santa Claus', 'Groundhog day': 'Groundhog Day',
        'Leap day': 'Leap Day', 'Burns night': 'Burns Night',
    }
    return known_caps.get(w.lower(), w)

def gen_batch(num, cat_id, recs_data):
    """recs_data is a list of tuples: (word, sub, diff, desc, tags, hints, imposters)"""
    recs = []
    for rd in recs_data:
        word, sub, diff, desc, tags, hints, imposters = rd
        w = fix_word(word)
        recs.append({
            "word": w,
            "category": cat_id,
            "subcategory": sub,
            "difficulty": diff,
            "description": desc,
            "tags": tags,
            "hints": hints,
            "imposters": imposters
        })
    errs_count = 0
    warns_count = 0
    clean_recs = []
    for r in recs:
        errs, warns = W.validate_record(r, cats, lists)
        if errs:
            print(f'FAIL: {r["word"]} -> {errs}')
            errs_count += 1
        elif warns:
            print(f'WARN: {r["word"]} -> {warns}')
            warns_count += 1
        else:
            clean_recs.append(r)
    return clean_recs, errs_count, warns_count

