"""Builds assets/synonyms.txt: other names for every game word, so a hint or
imposter word can never be the secret word under another name
(Eggplant -> "Aubergine"). The app uses it in offline, online and My Words.

Line formats:
  `word: name, name`  true other names (manual list) - blocked as hints AND
                      as imposter words.
  `word ~ name, name` looser Datamuse noun synonyms - blocked as hints only,
                      so close-but-different imposter words (Toad/Frog) stay.

Sources: tool/words/synonyms_manual.txt (regional names) + the free Datamuse
API (rel_syn, the same source online mode uses). Datamuse answers are cached in
tool/words/synonyms_cache_v2.json, so re-runs only query new words.

Usage (from repo root):  python tool/words/build_synonyms.py
"""
import concurrent.futures as cf
import glob
import json
import os
import sys
import urllib.parse
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wordlib as W  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
CACHE = os.path.join(HERE, 'synonyms_cache_v2.json')
MANUAL = os.path.join(HERE, 'synonyms_manual.txt')
OUT = os.path.join(W.ROOT, 'assets', 'synonyms.txt')


def game_words():
    words = set()
    for p in W.iter_source_files():
        words |= {r['word'] for r in W.load_records(p)}
    for p in glob.glob(os.path.join(HERE, 'legacy', '*.json')):
        if not os.path.basename(p).startswith('_'):
            with open(p, encoding='utf8') as f:
                words |= {w['word'] for w in json.load(f)['words']}
    return sorted(words, key=str.lower)


def datamuse(word):
    url = 'https://api.datamuse.com/words?' + urllib.parse.urlencode({'rel_syn': word, 'max': 20, 'md': 'p'})
    req = urllib.request.Request(url, headers={'User-Agent': 'word-tool/1.0'})
    for _ in range(3):
        try:
            with urllib.request.urlopen(req, timeout=20) as r:
                # Nouns only: verb/adjective senses ("Sweeping", "Crying") are fine hints.
                return [d['word'] for d in json.loads(r.read())
                        if 'n' in d.get('tags', []) and not d['word'].endswith('ing')]
        except Exception:  # noqa: BLE001
            continue
    return None


def main():
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except AttributeError:
        pass
    cache = {}
    if os.path.exists(CACHE):
        with open(CACHE, encoding='utf8') as f:
            cache = json.load(f)
    words = game_words()
    todo = [w for w in words if W.normalize(w) not in cache]
    print('%d words, %d to look up' % (len(words), len(todo)))
    failed = 0
    with cf.ThreadPoolExecutor(8) as ex:
        for i, (w, syns) in enumerate(zip(todo, ex.map(datamuse, todo)), 1):
            if syns is None:
                failed += 1
                continue
            cache[W.normalize(w)] = syns
            if i % 200 == 0:
                print('  %d/%d' % (i, len(todo)))
    with open(CACHE, 'w', encoding='utf8') as f:
        json.dump(cache, f, ensure_ascii=False, indent=0, sort_keys=True)

    lines = ['# Generated by tool/words/build_synonyms.py - edit synonyms_manual.txt instead.']
    with open(MANUAL, encoding='utf8') as f:
        lines += [l.strip() for l in f if l.strip() and not l.startswith('#')]
    for w in words:
        key = W.normalize(w)
        syns = [s for s in cache.get(key, [])
                if W.normalize(s) != key and len(s.split()) <= 3 and ',' not in s and ':' not in s]
        if syns:
            lines.append('%s ~ %s' % (key, ', '.join(syns)))
    with open(OUT, 'w', encoding='utf8') as f:
        f.write('\n'.join(lines) + '\n')
    print('Wrote %s (%d groups)%s' % (OUT, len(lines) - 1,
          '; %d lookups failed, re-run to retry' % failed if failed else ''))


if __name__ == '__main__':
    main()
