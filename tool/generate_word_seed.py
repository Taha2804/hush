"""Generates the Supabase word bank seed from assets/packs.

Run from the repo root after changing the packs:
    python tool/generate_word_seed.py
"""
import glob
import json
import os

OUT = "supabase/migrations/20261111000200_word_bank_seed.sql"

rows = []
for path in sorted(glob.glob("assets/packs/*.json")):
    if os.path.basename(path) == "index.json":
        continue
    with open(path, encoding="utf8") as f:
        pack = json.load(f)
    for w in pack["words"]:
        hints = sorted(w.get("hints", []), key=lambda h: h.get("level", 0))
        seen, parts = set(), []
        for h in hints:
            t = h["text"].strip()
            if t and t.lower() not in seen:
                seen.add(t.lower())
                parts.append(t)
        rows.append({
            "d": (w.get("description") or " • ".join(parts)).strip(),
            "c": pack["name"],
            "w": w["word"],
            "h": [h["text"] for h in w.get("hints", []) if h.get("level") == 2],
            "f": w.get("fakes", []),
        })

data = json.dumps(rows, ensure_ascii=False, separators=(",", ":"))
tag = "$seed$"
assert tag not in data

sql = f"""-- GENERATED by tool/generate_word_seed.py. Do not edit by hand. Safe to re-run.
alter table private.word_bank add column if not exists description text;

insert into private.word_bank (category, word, hints, fakes, description)
select r.c, r.w,
       array(select jsonb_array_elements_text(r.h)),
       array(select jsonb_array_elements_text(r.f)),
       nullif(r.d, '')
from jsonb_to_recordset({tag}{data}{tag}::jsonb) as r(c text, w text, h jsonb, f jsonb, d text)
on conflict (category, word) do update
set hints = excluded.hints, fakes = excluded.fakes, description = excluded.description;
"""

with open(OUT, "w", encoding="utf8", newline="\n") as f:
    f.write(sql)
print(f"{len(rows)} words, {len(sql) // 1024} KB -> {OUT}")
